const templateByName = Object.fromEntries(EVENT_TEMPLATES.map((t) => [t.name, t]));

function event(
  id: string,
  name: string,
  extra?: Partial<WeddingEvent>,
): WeddingEvent {
  const template = templateByName[name];
  return {
    id,
    name,
    date: null,
    startTime: '',
    endTime: '',
    venue: '',
    description: template?.description ?? '',
    expectedGuests: null,
    budget: null,
    responsibleId: null,
    status: 'Planning',
    checklist: checks(template?.checklist ?? []),
    vendors: '',
    notes: 'Sample ceremony. Set the date after you confirm the wedding date. Nothing here is booked.',
    isDemo: true,
    ...extra,
  };
}


function mediaEvent(name: string): string | null {
  if (name.includes('Sangeet')) return 'e-sangeet';
  if (name.includes('Reception')) return 'e-reception';
  if (name.includes('shoot') || name.includes('highlight') || name === 'Photography' || name === 'Videography' || name.includes('Edited')) {
    return 'e-wedding';
  }
  return null;
}

